"""TikTok discovery engine: search -> candidate creator profiles -> Mongo.

Also owns the browser session (login/checkpoint detection) and the payload
parsing (TikTokUser + friends): both are produced here first and re-used by
analysis_engine.py, which imports them rather than redefining them, so
there is exactly one definition of each across the two files.

WHY THIS DRIVES A REAL BROWSER RATHER THAN CALLING AN API DIRECTLY
    TikTok publishes no free, stable public API for search or profile
    lookup. Every "TikTok API" advertised online is either a paid reseller
    wrapping the same scraping this module does, or a raw replication of
    TikTok's own private request signing (X-Bogus, msToken, _signature),
    generated by TikTok's own JavaScript at runtime from browser
    fingerprinting, and changed on TikTok's own schedule, not ours.
    Reverse-engineering that signature is exactly the "breaks without
    warning every few months" maintenance burden every OTHER platform in
    this engine avoids by driving a real logged-in browser instead and
    letting the platform's own frontend do the signing for us (see
    stealth/browser.py). TikTok gets the same treatment here, not a
    different one.

WHERE THE DATA ACTUALLY COMES FROM, IN ORDER
    1. TikTok server-renders its own initial page state into a `<script>`
       tag on every page, `__UNIVERSAL_DATA_FOR_REHYDRATION__` on current
       builds, `SIGI_STATE` on older ones/behind experiments. A profile
       page's user info AND a search page's first batch of results both
       arrive this way, in the SAME response as the HTML, no XHR race to
       wait on. This is the primary source, and deliberately mirrors the
       hard lesson already learned in instagram/analysis_engine.py: passive
       network interception of a payload that may not fire reliably is not
       something to build the primary path around.
    2. Network responses matching TikTok's own `/api/search/...` calls,
       intercepted passively while scrolling, the second page of results
       onward arrives this way, since the hydration script only ever
       carries the first batch.
    3. When both of the above come up empty. TikTok strips the hydration
       payload from traffic its own bot-scoring doesn't like, leaving a
       skeleton page with no counts, this falls back to reading the
       rendered results directly: anchors linking to `/@<username>`, the
       one thing a results page cannot hide, since a clickable result IS a
       link to a profile.

NEEDS LIVE VERIFICATION. Every field name below (`uniqueId`, `avatarLarger`,
`followerCount`, ...) is reverse-engineered from public write-ups, not
captured from a live authenticated session the way every other platform's
parsing in this codebase was. The DOM fallback and the run_strategies chain
exist specifically so a wrong guess here degrades to fewer fields rather
than to zero results reported as a clean success, but this module should
not be trusted in production before a real session confirms it end to end
(see registry.py's `stability_note` for this platform).
"""

